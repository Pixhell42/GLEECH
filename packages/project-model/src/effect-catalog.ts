export function filterEffectCatalog(
  search: string,
  category: EffectCategory = 'All',
): EffectType[] {
  const terms = search.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return (Object.keys(EFFECT_DEFINITIONS) as EffectType[])
    .filter((type) => {
      const definition = EFFECT_DEFINITIONS[type];
      const text =
        `${definition.title} ${definition.description} ${EFFECT_CATEGORY[type]} ${aliases[type] ?? ''}`.toLocaleLowerCase();
      return (
        (category === 'All' || EFFECT_CATEGORY[type] === category) &&
        terms.every((term) => text.includes(term))
      );
    })
    .sort((a, b) =>
      EFFECT_DEFINITIONS[a].title.localeCompare(EFFECT_DEFINITIONS[b].title, 'en', {
        sensitivity: 'base',
        numeric: true,
      }),
    );
}
