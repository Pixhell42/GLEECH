import type { ParameterDefinition } from './index';

const n = (
  label: string,
  value: number,
  min: number,
  max: number,
  description: string,
  unit: 'percent' | 'count' | 'degrees' | 'multiplier' | 'coordinate' = 'percent',
): ParameterDefinition => ({
  kind: 'number',
  label,
  default: value,
  min,
  max,
  step: unit === 'count' || unit === 'degrees' ? 1 : unit === 'coordinate' ? 0.00001 : 0.01,
  unit,
  description,
});
const choice = (
  label: string,
  values: readonly string[],
  description: string,
): ParameterDefinition => ({
  kind: 'choice',
  label,
  default: values[0]!,
  options: values.map((value) => ({ value, label: value[0]!.toUpperCase() + value.slice(1) })),
  description,
});
