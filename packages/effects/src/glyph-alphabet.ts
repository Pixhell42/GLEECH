export function bitmapRows(character: string): readonly number[] {
  return letters[character] ?? letters['◇']!;
}
export function bitmapDensity(character: string): number {
  return bitmapRows(character).reduce(
    (sum, row) => sum + row.toString(2).replaceAll('0', '').length,
    0,
  );
}
export function densityRanked(text: string): string[] {
  return Array.from(text)
    .map((character, index) => ({ character, index, density: bitmapDensity(character) }))
    .sort((a, b) => a.density - b.density || a.index - b.index)
    .map((g) => g.character);
}
