// Distinct original lower-case forms where possible, otherwise small capitals.
for (const [upper, rows] of Object.entries(letters))
  if (/^[A-Z]$/.test(upper)) letters[upper.toLowerCase()] = [0, 0, ...rows.slice(2)];
export const EXTENDED_REPERTOIRE = ' .·:-=+*%#@│─┌┐└┘┼╬░▒▓▄▀█';
