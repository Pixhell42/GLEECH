// Reproducible 64x64 toroidal void-and-cluster rank tile (sigma 1.5).
// Algorithm: R. Ulichney, 1993/1994, https://cv.ulichney.com/papers/1994-filter-design.pdf
import { writeFile } from 'node:fs/promises';
const size = 64,
  total = size * size;
let seed = 8172;
const random = () => {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  return (seed >>> 0) / 2 ** 32;
};
const positions = Array.from({ length: total }, (_, i) => i);
for (let i = total - 1; i > 0; i--) {
  const j = Math.floor(random() * (i + 1));
  [positions[i], positions[j]] = [positions[j], positions[i]];
}
const initial = new Uint8Array(total);
for (const i of positions.slice(0, total / 4)) initial[i] = 1;
const kernel = [];
for (let y = -7; y <= 7; y++)
  for (let x = -7; x <= 7; x++) kernel.push([x, y, Math.exp(-(x * x + y * y) / (2 * 1.5 ** 2))]);
const energy = new Float64Array(total);
function change(i, delta) {
  const x = i % size,
    y = Math.floor(i / size);
  for (const [dx, dy, w] of kernel)
    energy[((y + dy + size) % size) * size + ((x + dx + size) % size)] += delta * w;
}
for (let i = 0; i < total; i++) if (initial[i]) change(i, 1);
function extreme(bits, occupied, max) {
  let best = -1,
    value = max ? -Infinity : Infinity;
  for (let i = 0; i < total; i++)
    if (bits[i] === occupied && (max ? energy[i] > value : energy[i] < value)) {
      best = i;
      value = energy[i];
    }
  return best;
}
let iterations = 0;
for (; iterations < total * 20; iterations++) {
  const cluster = extreme(initial, 1, true);
  initial[cluster] = 0;
  change(cluster, -1);
  const hole = extreme(initial, 0, false);
  initial[hole] = 1;
  change(hole, 1);
  if (hole === cluster) break;
}
if (iterations === total * 20) throw new Error('Void/cluster relaxation did not converge.');
const stableEnergy = energy.slice(),
  ranks = new Uint16Array(total),
  bits = initial.slice();
for (let rank = total / 4 - 1; rank >= 0; rank--) {
  const i = extreme(bits, 1, true);
  ranks[i] = rank;
  bits[i] = 0;
  change(i, -1);
}
energy.set(stableEnergy);
bits.set(initial);
for (let rank = total / 4; rank < total / 2; rank++) {
  const i = extreme(bits, 0, false);
  ranks[i] = rank;
  bits[i] = 1;
  change(i, 1);
}
// Above 50%, rank the complementary minority pattern by removing its clusters.
for (let i = 0; i < total; i++) bits[i] = 1 - bits[i];
energy.fill(0);
for (let i = 0; i < total; i++) if (bits[i]) change(i, 1);
for (let rank = total / 2; rank < total; rank++) {
  const i = extreme(bits, 1, true);
  ranks[i] = rank;
  bits[i] = 0;
  change(i, -1);
}
const rows = Array.from(
  { length: size },
  (_, y) => '  ' + [...ranks.slice(y * size, (y + 1) * size)].join(', ') + ',',
);
await writeFile(
  'packages/effects/src/blue-noise.ts',
  '// Generated by tooling/generate-blue-noise.mjs. Seed 8172, toroidal sigma 1.5.\n// Ulichney void-and-cluster: https://cv.ulichney.com/papers/1994-filter-design.pdf\nexport const BLUE_NOISE_SIZE = 64;\nexport const BLUE_NOISE_RANKS = new Uint16Array([\n' +
    rows.join('\n') +
    '\n]);\n',
);
console.log('Generated 4096 blue-noise ranks; relaxation iterations:', iterations);
